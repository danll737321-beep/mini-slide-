#!/usr/bin/env python3
"""Bundle content/<deck>/ (deck.json + slides/*.html) into data/decks.js.

Usage:  python3 tools/build.py
Add a deck: drop its folder in content/, reference it in content/catalog.json, rebuild.
"""
import json, re, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
CONTENT = ROOT / "content"

ICONS = {
    "Lightbulb": "M9 18h6M10 22h4M12 2a7 7 0 0 0-4 12.7V17h8v-2.3A7 7 0 0 0 12 2z",
    "Home": "M3 10.5 12 3l9 7.5V21H3zM9 21v-6h6v6",
    "Lightning": "M13 2 3 14h9l-1 8 10-12h-9l1-8z",
    "Chart": "M3 3v18h18M7 16v-5M12 16V8M17 16V7",
    "Chat": "M21 12a8 8 0 0 1-11.6 7.1L3 21l1.9-6.4A8 8 0 1 1 21 12z",
    "Activity": "M22 12h-4l-3 9L9 3l-3 9H2",
    "Search": "M11 4a7 7 0 1 0 0 14 7 7 0 0 0 0-14zM21 21l-5-5",
    "Warning": "M12 3 2 21h20L12 3zM12 10v5M12 18h.01",
    "Users": "M16 21v-2a4 4 0 0 0-4-4H6a4 4 0 0 0-4 4v2M9 11a4 4 0 1 0 0-8 4 4 0 0 0 0 8zM22 21v-2a4 4 0 0 0-3-3.9M16 3.1a4 4 0 0 1 0 7.8",
    "Play": "M6 4l14 8-14 8z",
    "Link": "M10 13a5 5 0 0 0 7.5.5l3-3a5 5 0 0 0-7-7l-1.7 1.7M14 11a5 5 0 0 0-7.5-.5l-3 3a5 5 0 0 0 7 7l1.7-1.7",
}

def icon(m):
    name, style = m.group(1), m.group(2)
    d = ICONS.get(name, "M12 3a9 9 0 1 0 0 18 9 9 0 0 0 0-18z")
    return (f'<svg aria-hidden="true" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
            f'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" style="flex:none;{style}">'
            f'<path d="{d}"/></svg>')

def shape(m):
    style = m.group(2)
    return ('<div aria-hidden="true" style="flex:none;clip-path:polygon(0 32%,62% 32%,62% 0,100% 50%,62% 100%,62% 68%,0 68%);'
            f'{style}"></div>')

def clean(html):
    html = re.sub(r'<x-icon name="(\w+)" style="([^"]*)"></x-icon>', icon, html)
    html = re.sub(r'<x-shape kind="([\w-]+)" style="([^"]*)"></x-shape>', shape, html)
    return html.strip()

def main():
    catalog = json.loads((CONTENT / "catalog.json").read_text())
    decks, fonts = {}, set()
    for cat in catalog["categories"]:
        for lesson in cat["lessons"]:
            for lang, deck_id in lesson["versions"].items():
                meta = json.loads((CONTENT / deck_id / "deck.json").read_text())
                for f in meta.get("faces", {}).values():
                    fonts.add(f["href"])
                slides = []
                for sid in meta["order"]:
                    html = (CONTENT / deck_id / "slides" / f"{sid}.html").read_text()
                    note = re.search(r"<aside>(.*?)</aside>", html, re.S)
                    slides.append({"id": sid, "html": clean(re.sub(r"<aside>.*?</aside>", "", html, flags=re.S)),
                                   "note": note.group(1).strip() if note else ""})
                decks[deck_id] = {"title": meta["title"], "lang": lang, "slides": slides}
    out = ROOT / "data" / "decks.js"
    out.parent.mkdir(exist_ok=True)
    out.write_text("// Generated by tools/build.py — edit content/ and rebuild.\n"
                   f"window.CATALOG = {json.dumps(catalog, ensure_ascii=False)};\n"
                   f"window.DECKS = {json.dumps(decks, ensure_ascii=False)};\n"
                   f"window.DECK_FONTS = {json.dumps(sorted(fonts))};\n")
    print(f"{len(decks)} decks, {sum(len(d['slides']) for d in decks.values())} slides -> {out.relative_to(ROOT)}")

if __name__ == "__main__":
    main()
